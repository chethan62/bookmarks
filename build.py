#!/usr/bin/env python3
"""Regenerate importable bookmark files from README.md (single source of truth).

  python3 build.py            -> bookmarks.html  (public, committed)
  python3 build.py --source ~/bookmarks-export.html
                              -> PRIVATE.html   (local only, gitignored)

Import: Firefox > Bookmarks > Manage bookmarks > Import and Backup >
Import Bookmarks from HTML. Chrome > Bookmark manager > kebab > Import bookmarks.
"""
import html, re, sys, time
from pathlib import Path

ROOT = Path(__file__).parent
README = ROOT / "README.md"


def readme_categories():
    """[(folder, [(title, url)])] — one folder per README group, in README order."""
    text = README.read_text(encoding="utf-8")
    head, _, tail = text.partition("## Handy sites")
    cats = []
    games = re.findall(r"^\| \d+ \| \[([^\]]+)\]\((https?://[^)\s]+)\)", head, re.M)
    if games:
        cats.append(("Linux Games", games))
    group = None
    for line in tail.splitlines():
        if line.startswith("## "):
            break
        if m := re.match(r"\*\*(.+?)\*\*", line.strip()):   # allow "**Name** — note"
            group = m.group(1)
            cats.append((group, []))
        elif group and line.startswith("- "):
            cats[-1][1].extend(re.findall(r"\[([^\]]+)\]\((https?://[^)\s]+)\)", line))
    assert cats and all(items for _, items in cats), cats  # crash loudly, not write an empty import
    return [(f, items) for f, items in cats]


def netscape(folders):
    ts = int(time.time())
    out = ["<!DOCTYPE NETSCAPE-Bookmark-file-1>",
           "<!-- This is an automatically generated file. -->",
           '<META HTTP-EQUIV="Content-Type" CONTENT="text/html; charset=UTF-8">',
           "<TITLE>Bookmarks</TITLE>", "<H1>Bookmarks Menu</H1>", "", "<DL><p>"]
    for folder, items in folders:
        out.append(f'    <DT><H3 ADD_DATE="{ts}">{html.escape(folder)}</H3>')
        out.append("    <DL><p>")
        for title, url in items:
            out.append(f'        <DT><A HREF="{html.escape(url, quote=True)}" ADD_DATE="{ts}">'
                       f"{html.escape(title)}</A>")
        out.append("    </DL><p>")
    out += ["</DL><p>", ""]
    return "\n".join(out)


def private_folders(source):
    """Original Firefox export minus whatever the public README already lists."""
    published = {u for _, items in readme_categories() for _, u in items}
    seen, folders = set(), {}
    for folder, title, url in parse_netscape(Path(source).read_text(encoding="utf-8", errors="replace")):
        host = re.sub(r"^https?://(www\.)?", "", url).split("/")[0].lower()
        if "mozilla.org" in host or host in seen or url in published:
            continue
        seen.add(host)
        folders.setdefault(folder, []).append((title, url))
    return list(folders.items())


def parse_netscape(text):
    """-> [(folder/path, title, url)]; minimal, enough to round-trip our own output."""
    from html.parser import HTMLParser

    class P(HTMLParser):
        stack, rows, cur = [], [], None

        def handle_starttag(self, tag, attrs):
            d = dict(attrs)
            self.cur = ("h", d) if tag == "h3" else ("a", d) if tag == "a" else None

        def handle_data(self, data):
            if not (self.cur and data.strip()):
                return
            kind, d = self.cur
            if kind == "h":
                self.stack.append(data.strip())
            else:
                self.rows.append(("/".join(self.stack) or "ROOT", data.strip(), d.get("href", "")))
            self.cur = None

        def handle_endtag(self, tag):
            if tag == "dl" and self.stack:
                self.stack.pop()

    p = P()
    p.feed(text)
    return p.rows


def main():
    folders = readme_categories()
    pub = netscape(folders)
    assert pub.count("<DL><p>") == pub.count("</DL><p>"), "unbalanced DL — Firefox import would nest wrong"
    (ROOT / "bookmarks.html").write_text(pub, encoding="utf-8")

    # verify the file we just wrote parses back to exactly what we meant
    back = parse_netscape(pub)
    assert len(back) == sum(len(i) for _, i in folders), (len(back), folders)
    assert {u for _, _, u in back} == {u for _, items in folders for _, u in items}
    print(f"bookmarks.html: {len(folders)} folders, {len(back)} links")

    if "--source" in sys.argv:
        src = sys.argv[sys.argv.index("--source") + 1]
        priv = private_folders(src)
        priv_html = netscape(priv)
        (ROOT / "PRIVATE.html").write_text(priv_html, encoding="utf-8")
        (ROOT / "PRIVATE.md").write_text(
            "# Private / local bookmarks\n\nGitignored — never published. Generated by `build.py`.\n\n"
            + "\n".join(f"## {f}\n\n" + "\n".join(f"- {t} — {u}" for t, u in items) + "\n"
                        for f, items in priv), encoding="utf-8")
        n = sum(len(i) for _, i in priv)
        assert len(parse_netscape(priv_html)) == n
        print(f"PRIVATE.html + PRIVATE.md: {len(priv)} folders, {n} links (gitignored)")


if __name__ == "__main__":
    main()
